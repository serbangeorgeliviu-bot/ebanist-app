  function esc(s) {
    return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
  }
  function md(s) { return esc(s).replace(/\*\*([^*]+)\*\*/g, "<b>$1</b>"); }
  function plain(s) { return String(s).replace(/\*\*/g, ""); }
  function lang(l) { return LANGS.indexOf(l) >= 0 ? l : "en"; }
  function tx(o, l) { return o.t[lang(l)] || o.t.en; }
  function ui(l) { return UI[lang(l)]; }

  /* captura unui subiect: AVIF cu rezervă WebP. `dir` = dosarul cu limbi
     (aplicația și site-ul au aceeași origine: /site/screens/). */
  function figure(topic, l, dir) {
    var s = topic.shot && SHOTS[topic.shot];
    if (!s) return "";
    var base = (dir || "/site/screens/") + lang(l) + "/" + s.n + "-" + s.w;
    return '<figure class="hp-fig hp-fig-' + (s.w > 1000 ? "wide" : "phone") + '"><picture>' +
      '<source type="image/avif" srcset="' + base + '.avif">' +
      '<img src="' + base + '.webp" width="' + s.w + '" height="' + s.h + '" alt="' + esc(plain(tx(topic, l).title)) + '" loading="lazy" decoding="async" onerror="this.closest(\'figure\').hidden=true">' +
      "</picture></figure>";
  }

  /* corpul unui subiect (fără titlu): lead, pași, sfat, captură */
  function topicBody(topic, l, o) {
    var c = tx(topic, l), h = '<p class="hp-lead">' + md(c.lead) + "</p><ol class=\"hp-steps\">";
    for (var i = 0; i < c.steps.length; i++) h += "<li>" + md(c.steps[i]) + "</li>";
    h += "</ol>";
    if (c.tip) h += '<p class="hp-tip">' + md(c.tip) + "</p>";
    return h + (o && o.noFig ? "" : figure(topic, l, o && o.dir));
  }
  function faqBody(f, l) { return "<p>" + md(tx(f, l).a) + "</p>"; }

  /* text simplu pentru căutare și pentru JSON-LD */
  function topicText(topic, l) {
    var c = tx(topic, l);
    return plain(c.title + " " + c.lead + " " + c.steps.join(" ") + " " + (c.tip || ""));
  }

